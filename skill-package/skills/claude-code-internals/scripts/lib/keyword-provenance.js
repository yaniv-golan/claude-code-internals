'use strict';
/**
 * keyword-provenance.js — which topic-index.json keywords are hand-written and
 * which scripts/prepare-lessons.js generated. Shared by prepare-lessons.js,
 * build.js and the query scripts (which print hand keywords only).
 *
 * THE HAND SOURCE. references/hand-keywords.json is the frozen snapshot of the
 * hand-written keywords: `keyword_map` (4,993 keys, in their original order,
 * with their original lesson lists) and `lesson_keywords` (each lesson's
 * original `keywords` array, keyed by lesson id). It was created once, from
 * topic-index.json at 6f9595c, and nothing writes it: no script has a path
 * that does, and HAND_SHA256 below pins its bytes, so an edit fails
 * `build.js --check`. Changing it is a code change to this file, never a data
 * edit that a run could bless.
 *
 * PROVENANCE is membership in the hand source, never inferred from the state
 * of topic-index.json: a keyword_map key is HAND if it is a key of
 * hand-keywords.json, GENERATED otherwise. The two sets are disjoint by
 * construction: the derivation never emits a key the hand source has, even
 * one no longer projected (a RETIRED hand key, below).
 *
 * THE PROJECTION. topic-index.json's keyword_map and lessons[].keywords are
 * build output. The hand part is the hand source projected onto the lessons
 * that exist now: each hand key keeps the live lessons of its list, in order,
 * and disappears when none is left (RETIRED); each live lesson gets its hand
 * keywords (none for a lesson the snapshot does not know). Deleting a lesson
 * therefore needs no keyword edit and no flag: the next prepare-lessons.js run
 * projects it away. With no lesson deleted, the projection is the snapshot
 * itself. The generated part (prepare-lessons.js) follows the hand part.
 * Lesson ids are the join key, so an id must never be reused for a different
 * lesson.
 *
 * `identifier_keys` and `vocab_keys` (per lesson) record the generated keys mapped to it. They are
 * derived output like the rest and --check compares it with the derivation, so
 * losing it fails the check and a plain run restores it; it cannot turn a
 * generated key into a hand key, because provenance does not come from it.
 * The query scripts read it (handKeywords) rather than loading the hand source.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const BOUNDARY_FIELD = 'keyword_boundary';
const HAND_FILE = 'hand-keywords.json';
/** sha256 of references/hand-keywords.json. The file is frozen; see the header. */
const HAND_SHA256 = '6d46c2947cd3b8a76bdbead3e6860482402780dac7a767dd9abffb4e2ff8032b';

const sha256 = (s) => crypto.createHash('sha256').update(s).digest('hex');

/**
 * Parse the hand source. Key order is read from the ordered tree
 * (check-json-format.js), because JSON.parse hoists integer-like keys (gate ids).
 * Node texts are kept so the projection re-emits the snapshot byte for byte.
 * @returns {{raw, sha256, keys: Array<{key, keyText, items: Array<{id, node}>}>,
 *            keySet: Set<string>, lessonKeywords: Map<number, Array<{value, node}>>}}
 */
function parseHandSource(raw) {
  const { parseOrdered } = require('../check-json-format.js');
  const tree = parseOrdered(raw);
  const get = (o, k) => { const e = o.entries.find(([q]) => q === JSON.stringify(k)); return e ? e[1] : null; };
  const kmap = get(tree, 'keyword_map');
  const lk = get(tree, 'lesson_keywords');
  if (!kmap || !lk) throw new Error(`${HAND_FILE} needs keyword_map and lesson_keywords`);
  const keys = kmap.entries.map(([kq, v]) => ({
    key: JSON.parse(kq), keyText: kq, items: v.items.map((node) => ({ id: Number(node.text), node })),
  }));
  const lessonKeywords = new Map(lk.entries.map(([idq, v]) => [
    Number(JSON.parse(idq)), v.items.map((node) => ({ value: JSON.parse(node.text), node })),
  ]));
  return { raw, sha256: sha256(raw), keys, keySet: new Set(keys.map((k) => k.key)), lessonKeywords };
}

/** Read and parse references/hand-keywords.json under `skillDir`. */
function loadHandSource(skillDir) {
  const abs = path.join(skillDir, 'references', HAND_FILE);
  let raw;
  try { raw = fs.readFileSync(abs, 'utf8'); } catch (e) {
    throw new Error(`${HAND_FILE} is missing (${e.code}): the frozen hand keywords cannot be regenerated by any script; restore it from git`);
  }
  return { abs, ...parseHandSource(raw) };
}

/** Errors when the hand source is not the frozen snapshot. */
function handSourceErrors(hand) {
  if (hand.sha256 === HAND_SHA256) return [];
  return [`${HAND_FILE} is not the frozen snapshot (sha256 ${hand.sha256.slice(0, 12)}, pinned ${HAND_SHA256.slice(0, 12)}). ` +
    'Hand keywords are never edited: restore it (git checkout) and let prepare-lessons.js derive keys from the lesson text'];
}

/**
 * The hand part of topic-index.json for the lessons in `liveIds`.
 * @returns {{keys: Array<{key, keyText, items}>, retired: Set<string>,
 *            lessonKeywords: (id) => Array<{value, node}>}}
 */
function projectHand(hand, liveIds) {
  const live = liveIds instanceof Set ? liveIds : new Set(liveIds);
  const keys = [];
  const retired = new Set();
  for (const k of hand.keys) {
    const items = k.items.filter((it) => live.has(it.id));
    if (items.length) keys.push({ ...k, items }); else retired.add(k.key);
  }
  return { keys, retired, lessonKeywords: (id) => hand.lessonKeywords.get(id) || [] };
}

/**
 * The hand-only index for `topic`'s lessons: what the derivation starts from.
 * A plain parsed topic-index shape: {lessons: [{...lesson, keywords}], keyword_map}.
 */
function handTopic(topic, hand) {
  const proj = projectHand(hand, topic.lessons.map((l) => l.id));
  const t = JSON.parse(JSON.stringify(topic));
  t.keyword_map = {};
  for (const k of proj.keys) t.keyword_map[k.key] = k.items.map((it) => it.id);
  for (const l of t.lessons) {
    l.keywords = proj.lessonKeywords(l.id).map((x) => x.value);
    delete l.identifier_keys;
    delete l.vocab_keys;
    delete l.vocab;
  }
  delete t[BOUNDARY_FIELD];
  return { topic: t, retired: proj.retired };
}

/** Keys a lesson records as generated: its identifier keys and its vocabulary keys. */
function lessonGenerated(lesson) {
  return new Set([...(lesson.identifier_keys || []), ...(lesson.vocab_keys || [])]);
}

/** A lesson's keywords without the generated ones (what the query scripts print). */
function handKeywords(lesson) {
  const gen = lessonGenerated(lesson);
  return (lesson.keywords || []).filter((k) => !gen.has(k));
}

module.exports = {
  BOUNDARY_FIELD, HAND_FILE, HAND_SHA256,
  parseHandSource, loadHandSource, handSourceErrors, projectHand, handTopic,
  lessonGenerated, handKeywords,
};
